"""Track which art is done and make ready-to-paste batches for the Gemini chat.

Done = an approved image exists in tools/art/reference/approved/<Mod>/<id>.jpg (or the id is in the
character's "keep" list, e.g. the Strikes). That folder is the single source of truth.

    python tools/art/batch.py status                     # writes docs/art-progress.md
    python tools/art/batch.py next --per-char 5          # writes docs/art-next-batch.md and remembers the batch
    python tools/art/batch.py install Golem haymaker img.jpg   # approve an image: copy, crop into the mod, mark done
    python tools/art/batch.py subjects                   # rewrites docs/art-subjects.md
"""
import argparse, json, re, shutil, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate_art as g  # noqa: E402

ROOT = g.ROOT
APPROVED = ROOT / "tools" / "art" / "reference" / "approved"
BATCH_FILE = ROOT / "tools" / "art" / "batch.json"
RARITY = {"Basic": 0, "Token": 1, "Common": 2, "Uncommon": 3, "Rare": 4}
KIND_ORDER = {"card": 0, "relic": 1, "power": 2, "charui_icon": 3, "charui_portrait": 4, "mod_image": 5}
SHORT_LAYOUT = {
    "Attack": "Dynamic action, white motion arcs, impact burst.",
    "Skill": "Calm defensive or utility moment, no punching; motion arcs only if something moves.",
    "Power": "Centered like an emblem, soft radiating glow, no motion arcs, no impact burst.",
}


def cfg_path(mod):
    return g.CFG_DIR / f"{mod.lower()}.json"


def done_ids(mod, cfg):
    files = {p.stem for p in (APPROVED / mod).glob("*.jpg")} if (APPROVED / mod).exists() else set()
    return files | set(cfg.get("keep", []))


def ordered(assets):
    def key(a):
        return (KIND_ORDER.get(a["kind"], 9), RARITY.get(a.get("rarity"), 5), a["idx"])
    for i, a in enumerate(assets):
        a["idx"] = i
    return sorted(assets, key=key)


def short_bg(text):
    return re.sub(r"Background: flat (.*?) field with darker angular streaks(.*?)\.", lambda m: f"Background: {m.group(1)}{m.group(2).replace(' and a soft', ', with a soft')}.", text)


def chat_line(n, a, cfg):
    scene = short_bg(cfg["overrides"].get(a["id"], a.get("text", "")))
    if a["kind"] == "card":
        ctype = a["ctype"] if a["ctype"] in SHORT_LAYOUT else "Skill"
        shots = g.SHARED.get("shots", {}).get(ctype)
        camera = ""
        who = cfg["name"].replace("The ", "")
        if shots and re.search(rf"{who}|\b(she|he|her|his)\b", scene, re.I) and not re.search(
                r"close-up|full-body|wide shot|medium shot|seen from|from above|from the side|low.angle|over-the-shoulder", scene, re.I):
            camera = shots[sum(map(ord, a["id"])) % len(shots)].capitalize() + ": "
        return f"{n}. {a['title']} ({ctype.lower()}, card art, landscape 4:3): {camera}{scene} {SHORT_LAYOUT[ctype]}"
    if a["kind"] in ("power", "relic", "charui_icon"):
        return (f"{n}. {a['title']} ({a['kind'].replace('charui_', '')}, square 1:1): a single game icon of {scene}, centered, thick dark outline, "
                "on a perfectly flat solid pure magenta (#FF00FF) background with no shadows and no streaks.")
    if a["kind"] == "charui_portrait":
        return f"{n}. Character select (tall portrait 2:3): {scene}."
    return f"{n}. Mod image (square 1:1): {scene}."


def header(cfg):
    return ("The attached images are style references only. Copy ONLY their rendering style: rough black ink outlines with ink "
            "hatching, cel shading with two or three tones per colour, grunge paper texture, saturated but slightly muted colours. "
            "Do NOT copy their subject, pose, framing, composition or background colour: every image must look clearly different "
            "from them.\n\n"
            "Every card image: a flat background colour crossed by jagged dark diagonal brush streaks. No text, letters, numbers, "
            "frame, border or UI. Playing cards show only suit symbols. Vary the camera from image to image.\n\n"
            f"Character: {cfg['character']}\n\n"
            "Draw the images below ONE AT A TIME, in order. Start with number 1. After each image, wait until I say \"next\".\n")


def cmd_status(_):
    out = ["# Art progress", "", "Generated by `python tools/art/batch.py status`. Done = approved image in "
           "`tools/art/reference/approved/<Mod>/` (or a fixed Strike).", ""]
    total_done = total = 0
    sections = []
    for mod in g.MODS:
        cfg, assets = g.discover(mod)
        done = done_ids(mod, cfg)
        assets = ordered(assets)
        d = [a for a in assets if a["id"] in done]
        t = [a for a in assets if a["id"] not in done]
        total_done += len(d); total += len(assets)
        sections += [f"## {cfg['name']}: {len(d)}/{len(assets)} done", "",
                     "**Done:** " + (", ".join(a["title"] for a in d) or "none"), "",
                     "**To do (in batch order):** " + ", ".join(f"{a['title']}" + ("" if a["kind"] == "card" else f" ({a['kind']})") for a in t), ""]
    out += [f"**Overall: {total_done}/{total}**", ""] + sections
    (ROOT / "docs" / "art-progress.md").write_text("\n".join(out), encoding="utf-8")
    print(f"{total_done}/{total} done -> docs/art-progress.md")


def cmd_next(args):
    out = ["# Next art batch", "",
           "One Gemini chat per character. Attach the three Strike images (tools/art/reference/style/) to the first message, "
           "paste the block, then type \"next\" after each image. Send the images back with the card names.", ""]
    batch = {}
    for mod in g.MODS:
        cfg, assets = g.discover(mod)
        done = done_ids(mod, cfg)
        todo = [a for a in ordered(assets) if a["id"] not in done][:args.per_char]
        if not todo:
            continue
        batch[mod] = [{"id": a["id"], "title": a["title"], "kind": a["kind"]} for a in todo]
        lines = [chat_line(i + 1, a, cfg) for i, a in enumerate(todo)]
        out += [f"## {cfg['name']}", "", "```", header(cfg), "\n\n".join(lines), "```", ""]
    BATCH_FILE.write_text(json.dumps(batch, indent=2) + "\n", encoding="utf-8")
    (ROOT / "docs" / "art-next-batch.md").write_text("\n".join(out), encoding="utf-8")
    print("batch:", {m: [x["id"] for x in v] for m, v in batch.items()})


def cmd_subjects(_):
    """Rewrite docs/art-subjects.md from the configs."""
    kinds = {"card": "Cards", "power": "Power icons", "relic": "Relic", "charui_icon": "Character icons",
             "charui_portrait": "Character select", "mod_image": "Mod image"}
    out = ["# Art subjects", "", "What each image will show. Edit a line in `tools/art/<character>.json` under `overrides` to change it; "
           "everything else (style, character look, reference images, layout per card type and a varied camera angle) is added "
           "automatically. Regenerate this list with `python tools/art/batch.py subjects`.", ""]
    for mod in g.MODS:
        cfg, assets = g.discover(mod)
        done = done_ids(mod, cfg)
        out += [f"## {cfg['name']}", ""]
        for k, title in kinds.items():
            rows = [a for a in ordered(assets) if a["kind"] == k]
            if not rows:
                continue
            out += [f"### {title}", "", "| Name | Type | Shows |", "|---|---|---|"]
            for a in rows:
                t = " ".join(filter(None, [a.get("rarity"), a.get("ctype")])) if k == "card" else ""
                shows = "(done)" if a["id"] in done else cfg["overrides"].get(a["id"], "").replace("|", "/")
                out.append(f"| {a['title']} | {t} | {shows} |")
            out.append("")
    (ROOT / "docs" / "art-subjects.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/art-subjects.md")


def cmd_install(args):
    cfg, assets = g.discover(args.mod)
    a = next((x for x in assets if x["id"] == args.id), None)
    if not a:
        sys.exit(f"unknown id {args.id} for {args.mod}")
    dest = APPROVED / args.mod / f"{args.id}.jpg"
    dest.parent.mkdir(parents=True, exist_ok=True)
    from PIL import Image
    Image.open(args.image).convert("RGB").save(dest, quality=92)
    g.process(a, dest)
    print(f"installed {args.mod}/{args.id} ({a['kind']})")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("status")
    sub.add_parser("subjects")
    n = sub.add_parser("next"); n.add_argument("--per-char", type=int, default=5)
    i = sub.add_parser("install"); i.add_argument("mod", choices=list(g.MODS)); i.add_argument("id"); i.add_argument("image")
    a = ap.parse_args()
    {"status": cmd_status, "next": cmd_next, "install": cmd_install, "subjects": cmd_subjects}[a.cmd](a)
