"""
Scores every "simple" card against the vanilla value curve (same model as STS2_Card_Balance_Baseline.xlsx)
and writes docs/BALANCE.md. A card is simple when its effect is only damage / block / draw / energy /
HP loss / standard powers, with no conditions or scaling.

    python tools/balance_report.py          # prints outliers, writes docs/BALANCE.md
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODS = ["Golem", "CardSharp", "Bard", "Falconer"]

W = dict(dmg=1.0, aoe=1.5, rnd=0.9, blk=1.2, drw=4.0, nrg=7.0, hp=-1.5, heal=1.5)
POWERS = {"VulnerablePower": 4.5, "WeakPower": 4.5, "StrengthPower": 6, "DexterityPower": 6, "PlatingPower": 3,
          "VigorPower": 1, "IntangiblePower": 15, "BlockNextTurnPower": 1.0, "DoomPower": 0.75}
KW = {"Exhaust": 3, "Ethereal": 1.5, "Retain": -1.5, "Innate": -1}
COEF = dict(base=7.11, lin=1.99, quad=1.97, Uncommon=2.55, Rare=5.22, Basic=-4.0, Common=0.0)
SIMPLE_CALLS = {"Hit", "Guard", "DrawCards", "Debuff", "DebuffAll", "Buff", "Energy", "LoseHp", "GuardAllies",
                "BuffAllies", "CommonActions.CardAttack", "CommonActions.CardBlock", "CommonActions.Draw",
                "CommonActions.Apply", "CommonActions.ApplySelf"}


def classes(src):
    """Yield (name, body) for every class with an explicit base(cost, CardType, CardRarity, Target) ctor."""
    for m in re.finditer(r"public sealed class (\w+) : \w+\s*\{", src):
        start = m.end()
        depth, i = 1, start
        while depth and i < len(src):
            depth += {"{": 1, "}": -1}.get(src[i], 0)
            i += 1
        body = src[start:i - 1]
        b = re.search(r"base\(\s*(\d+)\s*,\s*CardType\.(\w+)\s*,\s*CardRarity\.(\w+)\s*,\s*TargetType\.(\w+)", body)
        if b:
            yield m.group(1), body, int(b.group(1)), b.group(2), b.group(3), b.group(4)


def score(body, cost, rarity, target):
    play = body[body.find("OnPlay") if "OnPlay" in body else body.find("Effect("):]
    reasons = []
    if re.search(r"\bif\s*\(|\?\s", play) or "Calculated" in body:
        reasons.append("conditional/scaling")
    if re.search(r"LayCount|SetRank|RollRank|Buff<\w+>\(ctx, [^)]", body):
        reasons.append("special: Table/rank/scaled power")
    calls = set(re.findall(r"(?:await\s+)((?:CommonActions\.)?\w+)", play))
    other = {c for c in calls if c not in SIMPLE_CALLS}
    if other:
        reasons.append("special: " + ", ".join(sorted(other)))
    if reasons:
        return None, reasons

    def var(name):
        m = re.search(rf"With{name}\((-?\d+)", body)
        return int(m.group(1)) if m else 0
    repeat = re.search(r'WithVar\("Repeat",\s*(\d+)', body)
    hits = int(repeat.group(1)) if repeat else 1
    mult = W["aoe"] if target == "AllEnemies" else W["rnd"] if target == "RandomEnemy" else 1
    value = var("Damage") * hits * mult + var("Block") * W["blk"] + var("Cards") * W["drw"] + var("Energy") * W["nrg"]
    value += var("Heal") * W["heal"]
    hp = re.search(r'WithVar\("HpLoss",\s*(\d+)', body)
    if hp and "LoseHp" in play:
        value += int(hp.group(1)) * W["hp"]
    for p, amt in re.findall(r"WithPower<(\w+)>\((\d+)", body):
        if p not in POWERS:
            return None, [f"unpriced power {p}"]
        debuff = p in ("VulnerablePower", "WeakPower", "DoomPower")
        value += POWERS[p] * int(amt) * (W["aoe"] if debuff and "DebuffAll" in play else 1)
    exp = COEF["base"] + COEF["lin"] * cost + COEF["quad"] * cost ** 2 + COEF.get(rarity, 0)
    exp += sum(v for k, v in KW.items() if f"CardKeyword.{k}" in body)
    return (value, exp), []


def main():
    lines = ["# Balance report", "",
             "Generated by `tools/balance_report.py`. Simple cards are priced with the same model as the balance",
             "spreadsheet (1 point = 1 damage; Index = Value / Expected; 0.88–1.12 is on curve). Cards with",
             "conditions, scaling or unique effects are listed as \"judge manually\".", "",
             "**Known, deliberate outliers:** party-wide cards (Shared Foundations, Battle Cry, Crowd Pleaser) are scored",
             "for solo play and roughly double in co-op; Intangible cards (Indestructible, Fake Out) are underpriced by the",
             "model; 0-cost Card Sharp cards (Deal In, Quick Draw) also advance the Table toward a Showdown; Impregnable",
             "mirrors vanilla Impervious.", ""]
    for mod in MODS:
        src = "\n".join(p.read_text(encoding="utf-8") for p in (ROOT / mod).glob(f"{mod}Code/Cards/*.cs"))
        rows, manual = [], []
        for name, body, cost, ctype, rarity, target in classes(src):
            if rarity == "Token" or ctype == "Power":
                continue
            res, why = score(body, cost, rarity, target)
            if res is None:
                manual.append((name, rarity, why[0]))
            else:
                v, e = res
                rows.append((v / e, name, rarity, cost, v, e))
        rows.sort()
        flag = lambda i: "too strong?" if i >= 1.35 else "above" if i >= 1.12 else "on curve" if i >= 0.88 else "below" if i >= 0.7 else "weak"
        lines += [f"## {mod}", "", f"{len(rows)} simple cards scored, {len(manual)} to judge manually.", "",
                  "| Card | Rarity | Cost | Value | Expected | Index | Verdict |", "|---|---|---|---|---|---|---|"]
        for i, name, rarity, cost, v, e in rows:
            lines.append(f"| {name} | {rarity} | {cost} | {v:.1f} | {e:.1f} | {i:.2f} | {flag(i)} |")
        lines += ["", "<details><summary>Judge manually</summary>", "", ", ".join(f"{n} ({r})" for n, r, _ in manual), "", "</details>", ""]
        out = [(name, f"{i:.2f}", flag(i)) for i, name, *_ in rows if i < 0.75 or i >= 1.3]
        print(f"{mod}: {len(rows)} scored, outliers: {out}")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "BALANCE.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
